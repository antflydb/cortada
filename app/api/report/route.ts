function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character] || character);
}

function markdownReport(overview: Overview): string {
  const summary = overview.siteSummary;
  const latest = overview.analyses[0];
  const title = summary ? `${summary.project.brandName} site audit` : `${latest?.brandName || productConfig.name} AEO audit`;
  const lines = [
    `# ${title}`,
    "",
    `Generated by ${productConfig.name} on ${new Date().toISOString()}`,
    "",
    summary
      ? `**Site:** ${summary.project.rootUrl}  \n**Pages audited:** ${summary.pageCount}  \n**Average score:** ${summary.averageScore}/100  \n**Run status:** ${summary.run.status}`
      : latest ? `**Page:** ${latest.url}  \n**Score:** ${latest.score}/100` : "No audit evidence is available.",
    "",
    "## Priority findings",
    "",
  ];
  const findings = summary?.findings || latest?.suggestions.map((suggestion) => ({ ...suggestion, affectedPages: 1, totalPages: 1, urls: [latest.url] })) || [];
  for (const finding of findings) {
    lines.push(`### ${finding.title}`, "", `**${finding.severity.toUpperCase()} · ${finding.affectedPages}/${finding.totalPages} pages**`, "", finding.detail, "");
    for (const url of finding.urls.slice(0, 5)) lines.push(`- ${url}`);
    lines.push("");
  }
  if (summary?.comparison) {
    lines.push("## Change since the previous run", "", `- Score change: ${summary.comparison.scoreDelta >= 0 ? "+" : ""}${summary.comparison.scoreDelta}`, `- Resolved finding types: ${summary.comparison.resolvedFindings.length}`, `- New finding types: ${summary.comparison.newFindings.length}`, "");
  }
  lines.push("---", productConfig.showAntflyAttribution ? `${productConfig.footerText} · Powered by Antfly` : productConfig.footerText);
  return lines.join("\n");
}

